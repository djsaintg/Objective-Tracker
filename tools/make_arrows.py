"""Generates the pre-rotated waypoint arrow images used by the guide HUD.

Hytale UI markup can't rotate or tint elements, so the HUD swaps between DIRECTIONS images.
Arrow_00 points straight up (target ahead); each next one turns 360/DIRECTIONS degrees
clockwise. The colour is baked in too: green when the target is ahead, through yellow at
90 degrees, to red when it's behind you.

The shape is an Assassin's-Creed-style insignia: two curved blades meeting at a point, with a
diamond between them.

    python3 tools/make_arrows.py   (needs Pillow)
"""
import colorsys
import math
import pathlib

from PIL import Image, ImageChops, ImageDraw, ImageFilter

OUT = pathlib.Path(__file__).resolve().parent.parent / "src/main/resources/Common/UI/Custom/ObjectiveTracker"
DIRECTIONS = 64  # keep in sync with GuideHud.ARROW_DIRECTIONS
SS = 8  # supersampling factor for smooth edges
OUTLINE = (16, 18, 22, 240)


def quad(p0, c, p1, steps=24):
    """Points along a quadratic Bezier curve from p0 to p1 with control point c."""
    out = []
    for i in range(steps + 1):
        t = i / steps
        x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t ** 2 * p1[0]
        y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t ** 2 * p1[1]
        out.append((x, y))
    return out


def shapes():
    """Polygons in a -1..1 box (y down), pointing up."""
    apex = (0.0, -0.96)
    left = (
        quad(apex, (-0.66, -0.30), (-0.90, 0.86))  # outer edge
        + [(-0.90, 0.86), (-0.42, 0.94)]  # foot
        + quad((-0.42, 0.94), (-0.22, 0.02), (-0.05, -0.52))  # inner edge back up
    )
    right = [(-x, y) for x, y in left]
    diamond = [(0.0, -0.24), (0.15, 0.30), (0.0, 0.66), (-0.15, 0.30)]
    return [left, right, diamond]


def colour(degrees_off):
    """Green when facing the target, yellow at 90 degrees, red when it's behind."""
    t = (1 + math.cos(math.radians(degrees_off))) / 2  # 1 ahead .. 0 behind
    r, g, b = colorsys.hsv_to_rgb(t * 120 / 360, 0.85, 0.95)
    return int(r * 255), int(g * 255), int(b * 255), 255


def render(size, degrees):
    big = size * SS
    mask = Image.new("L", (big, big), 0)
    draw = ImageDraw.Draw(mask)
    a = math.radians(degrees)
    r = big / 2 * 0.80
    for poly in shapes():
        pts = []
        for x, y in poly:
            rx = x * math.cos(a) - y * math.sin(a)
            ry = x * math.sin(a) + y * math.cos(a)
            pts.append((big / 2 + rx * r, big / 2 + ry * r))
        draw.polygon(pts, fill=255)

    # Dark rim around the shape so it reads on any background.
    rim = mask.filter(ImageFilter.MaxFilter(SS * 3 + 1))
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    img.paste(Image.new("RGBA", (big, big), OUTLINE), mask=rim)
    img.paste(Image.new("RGBA", (big, big), colour(degrees)), mask=mask)
    # Slightly darker lower half for a bit of depth.
    shade = Image.linear_gradient("L").rotate(-degrees, resample=Image.BICUBIC).resize((big, big))
    shade = ImageChops.multiply(shade.point(lambda v: int(v * 0.35)), mask)
    img.paste(Image.new("RGBA", (big, big), (0, 0, 0, 255)), mask=shade)
    return img.resize((size, size), Image.LANCZOS)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("Arrow_*.png"):
        old.unlink()
    step = 360 / DIRECTIONS
    for i in range(DIRECTIONS):
        render(48, i * step).save(OUT / f"Arrow_{i:02d}.png")
        render(96, i * step).save(OUT / f"Arrow_{i:02d}@2x.png")
    write_ui()
    print(f"wrote {DIRECTIONS * 2} images and GuideArrow.ui to {OUT}")


def write_ui():
    lines = [
        "// Waypoint arrow for the Objective Tracker guide panel. Generated by tools/make_arrows.py.",
        f"// The server shows exactly one of the {DIRECTIONS} pre-rotated images (UI elements can't be",
        "// rotated); 00 = target straight ahead, counting clockwise.",
        "Group #OtArrow {",
        "  Anchor: (Width: 44, Height: 44);",
        "",
    ]
    for i in range(DIRECTIONS):
        lines += [
            f"  Group #OtArrow{i:02d} {{",
            f'    Background: "Arrow_{i:02d}.png";',
            f"    Visible: {'true' if i == 0 else 'false'};",
            "  }",
            "",
        ]
    lines[-1:] = ["}", ""]
    (OUT / "GuideArrow.ui").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
